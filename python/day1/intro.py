# how to write a python program?
# 1. open a text editor or an integrated development environment (IDE) such as PyCharm, Visual Studio Code, or Jupyter Notebook.
# 2. create a new file and save it with a .py extension, for example, hello.py.
# 3. write your python code in the file, for example: print("Hello, world!")   
# 4. save the file.
# 5. run the python program using the command line or terminal by typing: python hello.py
# 6. you should see the output "Hello, world!" in the terminal.

