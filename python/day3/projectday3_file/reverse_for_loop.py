# Question -> # 3. write a python program to print the numbers from 10 to 1 using for loop
#
# Answer -> 
for i in range(10, 0, -1):
    print(i)

# here is the explanation of the above code:
# why we use a word "i" in the above code?
# beacuse if i want to display any output so we need a variable( explain in day3/session.py) for store data therefore we use "i" in the above code.

# why we use range() function and what is the meaning of that number which has been written in these function?
# ans-> range() function is used to create a sequence of the numbers from start to end-1. And the number that is written in the above function is the end of the sequence of the numbers.
#      here "10" means that the start of the sequence of the numbers is 10 and the end of the sequence of the numbers is 0. And the step of the sequence of the numbers is -1.



