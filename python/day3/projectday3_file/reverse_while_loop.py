# Questions -># 4. write a python program to print the numbers from 10 to 1 using while loop
# ans->
i = 10

while i >= 0:
    print(i)   
    i -= 1

# Here is the explanation of the code in the requested Q&A format:

# Why we use a word that is "i" in the above code?
# ans-> i is a variable that stores the current number value for printing and counting down.
#
# Why we use "while i >= 0:" in the above code?
# ans-> This is the loop condition. The code inside runs repeatedly while i is 0 or greater, stopping when i becomes negative.
#
# Why we use "i -= 1" in the above code?
# ans-> This subtracts 1 from i each loop (i = i - 1). It makes i decrease so the loop ends after printing 10 to 0.
#
# Why we use number "10" in the above code?
# ans-> 10 is the starting point of the countdown sequence.
#
# Why we use number "0" in the above code?
# ans-> 0 is the end point. i >= 0 includes printing 0.
#
# What is the meaning and use of print(i) in the above code?
# ans-> print(i) outputs the value of i to the console/screen. Each iteration prints the next reverse number.


