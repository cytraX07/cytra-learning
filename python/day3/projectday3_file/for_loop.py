# ans -> range is function that is used to create a sequence of numbers.

# why we use a number that is "1" in the above code?
# ans -> 1 is the start of sequence of the numbers.

# why we use a number that is "11" in the above code?
# ans -> 11 is the end of the sequence of numbers.

# if the number "11" is the end of the sequence of the nubmber so why 11 not come in output?
# ans-> beacuse the range function is used to create a sequence of numbers from start to end-1 
