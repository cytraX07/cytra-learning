# Question -># 2. write a python program to print the numbers from 1 to 10 using while loop
# 
# Answer ->

i = 10

while i >= 1:
    print(i)
    i -= 1

# here the explanation of code:

# why we use a word that is "i" in the above code?
# ans-> because i is variable that is used to store the value of the number that is being printed>
#
# why we use a word that is "while" in the above code?
# ans-> because while is a loop that is used to repeat a block of code as long as a condition is true.
#
# why use a line that is "i += 1"? explain.
# ans-> because i += 1 is used to increment the value of the variable i by 1 each time the loop is executed. And "+=" means
#       that the variable is incremented by 1 each time the loop is executed.
#
# what is the meaning of these sign "<=" & "+="?
# ans-> "<=" means that the loop is executed as long as the value of the variable i is less than or equal to 10. 
#       "+=" means that the value of the variable i is incremented by 1 each time the loop is executed.


